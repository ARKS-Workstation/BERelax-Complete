#!/usr/bin/env node
/**
 * The ADR index is generated from the records, and a check fails when it is stale.
 *
 * `docs/adr/README.md` is a hand-written COMMENTARY table: one long paragraph per decision, written by
 * whoever made it, and it is the most useful thing in the directory. It is also the wrong artefact to
 * answer "which ADRs exist", because that answer is a fact about the filesystem and a hand-maintained
 * copy of it drifts the first time somebody adds a record in a hurry.
 *
 * So the two jobs are separated:
 *
 *   - `docs/adr/INDEX.md` is GENERATED, by this script, from each record's own front matter: the number,
 *     the title, the status, the date, the unit and what it covers. Nothing in it is typed by hand, so
 *     nothing in it can be wrong without the record being wrong.
 *   - `README.md` keeps the commentary, and `--check` holds its ROW SET equal to the records on disk.
 *     The set is stated once — by the filesystem — and both files derive from it, which is ADR 0062's
 *     shape: the equality is structural rather than a test between two hand-written lists.
 *
 * Generating the commentary instead was the obvious alternative and it is the wrong one twice over. It
 * would need a one-line summary field in every record, which is 74 paragraphs rewritten by somebody who
 * did not make the decisions; and a generated paragraph is exactly the part of an ADR that cannot be
 * generated, because the thing worth recording is the argument.
 *
 * ## Why `--check` and not a second gate script
 *
 * A generator with no check is a generator somebody runs once. A check with no generator is a
 * maintenance task. The emit/check pair is the shape `pnpm tokens` already uses in this repository, and
 * the reason it is one file is that the two must not be able to disagree about the format: a separate
 * checker would reimplement the rendering, and the first format change would make it fail on correct
 * output.
 *
 * Usage:
 *   `node scripts/gen-adr-index.mjs --emit`   writes docs/adr/INDEX.md
 *   `node scripts/gen-adr-index.mjs`          fails if INDEX.md is stale or README.md is incomplete
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const ADR_DIR = 'docs/adr'
const INDEX = 'docs/adr/INDEX.md'
const README = 'docs/adr/README.md'
const EMIT = process.argv.includes('--emit')

/** `0007-money-and-business-day-primitives.md`. Neither index is one of these. */
const RECORD = /^(\d{4})-.+\.md$/

const problems = []
const fail = (rule, where, detail) => problems.push(`${where}  [${rule}] ${detail}`)

const field = (text, name) => {
  const match = new RegExp(`^- \\*\\*${name}:\\*\\*\\s*(.+)$`, 'm').exec(text)
  return match?.[1]?.trim() ?? null
}

function records() {
  const found = []
  for (const file of readdirSync(join(ROOT, ADR_DIR)).sort()) {
    const match = RECORD.exec(file)
    if (match === null) continue
    const number = match[1]
    const text = readFileSync(join(ROOT, ADR_DIR, file), 'utf8')
    const heading = /^#\s+(.+)$/m.exec(text)?.[1]?.trim() ?? null
    if (number === undefined) continue
    if (heading === null) {
      fail('adr-record-has-no-heading', file, 'no `# ` heading, so the index has no title to show')
      continue
    }
    // `ADR 0007 — money is integer fils` → the part after the dash. The number is already a column, and
    // repeating it in the title is the kind of duplication a generated file should not contain.
    const title = heading.replace(/^ADR\s+\d{4}\s*[—-]\s*/u, '').trim()
    found.push({
      file,
      number,
      title,
      status: field(text, 'Status') ?? '(none)',
      date: field(text, 'Date') ?? '(none)',
      unit: field(text, 'Unit') ?? '(none)',
      covers: field(text, 'Covers') ?? '(none)',
    })
  }
  return found
}

/** A table cell: pipes escaped, newlines flattened. Nothing else, because nothing else is typed here. */
const cell = (value) =>
  value
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ')
    .trim()

function render(found) {
  const lines = [
    '<!-- GENERATED by scripts/gen-adr-index.mjs. Do not edit: `pnpm docs:adr` overwrites it and',
    '     `pnpm docs-set` fails while it is stale. The commentary lives in README.md, which is written by',
    '     hand on purpose — the argument behind a decision is the part that cannot be generated. -->',
    '',
    '# ADR index',
    '',
    `${found.length} records, generated from the front matter of each one. Every column below is read`,
    'out of the record it describes, so a row cannot be wrong without the record being wrong — which is',
    'the whole reason this file is not maintained by hand. For the argument behind any of them, read',
    '[README.md](README.md) and then the record.',
    '',
    '| # | Decision | Status | Date | Unit | Covers |',
    '|---|---|---|---|---|---|',
  ]
  for (const record of found) {
    lines.push(
      `| [${record.number}](${record.file}) | ${cell(record.title)} | ${cell(record.status)} | ` +
        `${cell(record.date)} | ${cell(record.unit)} | ${cell(record.covers)} |`,
    )
  }
  lines.push('')
  return lines.join('\n')
}

const found = records()

/*
  The floor (ADR 0002). An empty record set renders a valid, well-formed, completely empty index and
  `--check` would then report agreement between two files that describe nothing. Seventy-four exist; any
  reading below ten means the directory or the filename pattern is wrong.
*/
if (found.length < 10) {
  console.error(
    `The ADR index generator read ${found.length} record(s) from ${ADR_DIR}, which is too few to mean ` +
      'anything. The directory or the filename pattern is wrong, so an index generated from it would ' +
      'be an empty file that agrees with itself.',
  )
  process.exit(1)
}

const rendered = render(found)

if (EMIT) {
  writeFileSync(join(ROOT, INDEX), rendered)
  console.log(`Wrote ${INDEX}: ${found.length} record(s).`)
  process.exit(0)
}

// --- check 1: the generated index is current ------------------------------------------------------
{
  let current = null
  try {
    current = readFileSync(join(ROOT, INDEX), 'utf8')
  } catch {
    current = null
  }
  if (current === null) {
    fail('adr-index-missing', INDEX, 'does not exist. Run `pnpm docs:adr`')
  } else if (current !== rendered) {
    // The first differing line, because a whole-file diff in a gate's output is unreadable and the
    // first difference is almost always the added record.
    const a = current.split('\n')
    const b = rendered.split('\n')
    const at = a.findIndex((line, i) => line !== b[i])
    fail(
      'adr-index-stale',
      `${INDEX}:${at + 1}`,
      `is stale. Expected ${JSON.stringify(b[at] ?? '(end of file)')}, found ` +
        `${JSON.stringify(a[at] ?? '(end of file)')}. Run \`pnpm docs:adr\``,
    )
  }
}

// --- check 2: the commentary covers every record, in both directions ------------------------------
{
  const readme = readFileSync(join(ROOT, README), 'utf8')
  const linked = new Set([...readme.matchAll(/\[(\d{4})\]\((\d{4}-[^)]+\.md)\)/g)].map((m) => m[2]))
  for (const record of found) {
    if (linked.has(record.file)) continue
    fail(
      'adr-not-in-the-commentary',
      `${README} ${record.number}`,
      `${record.file} exists and README.md does not link it. A record nobody can find from the index ` +
        'is a decision the next person re-makes',
    )
  }
  const onDisk = new Set(found.map((r) => r.file))
  for (const file of linked) {
    if (onDisk.has(file)) continue
    fail(
      'adr-commentary-names-a-missing-record',
      `${README} ${file}`,
      'README.md links a record that is not on disk. This is the direction that lets the index shrink: ' +
        'a row describing a decision whose record was renamed or removed reads exactly like a live one',
    )
  }
  if (linked.size === 0) {
    fail(
      'adr-not-in-the-commentary',
      README,
      'no record links parsed out of the commentary at all, so the comparison above was about nothing',
    )
  }
}

if (problems.length > 0) {
  console.error('ADR index:\n')
  for (const problem of problems) console.error(`  ${problem}`)
  console.error(`\n${problems.length} problem(s).`)
  process.exit(1)
}

console.log(
  `ADR index: ${found.length} record(s), the generated index is current, and the commentary in ` +
    'README.md links every one of them and nothing else.',
)
