#!/usr/bin/env node
/**
 * `docs/operations/secret-inventory.md` is generated from `build/secret-inventory.json`.
 *
 * The inventory already exists as machine-readable data, and `check-secret-rotation.mjs` and
 * `check-processor-register.mjs` both read it. What it did not have was a form a person can read at
 * 02:00 while something is on fire — which is what H-HARD-09's documentation set is for, and which is
 * also the moment nobody is going to open a JSON file and count brackets.
 *
 * Writing that page by hand would be the second statement of a fact the brief warns about, and the copy
 * that drifts would be the one somebody reads under pressure. So it is generated, and `--check` fails
 * while it is stale: one source, two renderings, and a build that refuses to disagree with itself.
 *
 * ## What is NOT in the generated page
 *
 * No value, ever. Not a fragment, not a length, not a hash. The page lists names, what each key
 * controls, where it lives, who owns rotating it, how often, and the runbook heading that says how —
 * which is everything somebody needs to act and nothing that helps an attacker who has it.
 *
 * Usage:
 *   `node scripts/gen-secret-inventory.mjs --emit`   writes docs/operations/secret-inventory.md
 *   `node scripts/gen-secret-inventory.mjs`          fails if the page is stale
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const SOURCE = 'build/secret-inventory.json'
const PAGE = 'docs/operations/secret-inventory.md'
const EMIT = process.argv.includes('--emit')

const inventory = JSON.parse(readFileSync(join(ROOT, SOURCE), 'utf8'))
const entries = Array.isArray(inventory.entries) ? inventory.entries : []
const notSecrets = Array.isArray(inventory.notSecrets) ? inventory.notSecrets : []

/*
  The floor (ADR 0002). An empty or reshaped source renders a valid page listing nothing, and `--check`
  would then hold two files equal about no secrets at all — which is the one answer this page must not
  be able to give. Ten entries exist today.
*/
if (entries.length < 5) {
  console.error(
    `${SOURCE} yielded ${entries.length} entries, which is too few to mean anything. The file's shape ` +
      'has changed, so a page generated from it would list nothing and agree with itself.',
  )
  process.exit(1)
}

/** Pipes escaped and newlines flattened, because these are prose fields going into table cells. */
const cell = (value) =>
  String(value ?? '—')
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ')
    .trim()

/** `docs/runbooks/key-rotation.md#rotating-the-clinical-kek` → a link relative to `docs/operations/`. */
const rotationLink = (rotation) => {
  if (typeof rotation !== 'string' || rotation === '') return '—'
  const [path, anchor] = rotation.split('#')
  return `[${anchor ?? path}](../../${path}${anchor === undefined ? '' : `#${anchor}`})`
}

function render() {
  const lines = [
    '<!-- GENERATED by scripts/gen-secret-inventory.mjs from build/secret-inventory.json.',
    '     Do not edit: `pnpm docs:secrets` overwrites it and `pnpm docs-set` fails while it is stale.',
    '     The JSON is the source because two gates read it; this page exists because nobody reads JSON',
    '     at 02:00. NO VALUE of any secret appears here, in any form. -->',
    '',
    '# Environment and secret inventory',
    '',
    cell(inventory.about),
    '',
    'Generated from `build/secret-inventory.json`. `pnpm rotation` holds it against the secret-shaped',
    'names the code reads; `pnpm processors` holds it against the keys `packages/config/src/env.ts`',
    'declares, in both directions. Adding a credential therefore fails the build until its rotation is',
    'written down, which is the only moment the person who knows how it works is still looking at it.',
    '',
    '## What this system holds',
    '',
    `${entries.length} entries.`,
    '',
    '| Variable | Kind | Controls | Owner | Rotate every | Zero downtime | Procedure |',
    '|---|---|---|---|---|---|---|',
  ]
  for (const entry of entries) {
    lines.push(
      `| \`${cell(entry.env)}\` | ${cell(entry.kind)} | ${cell(entry.holds)} | ${cell(entry.owner)} ` +
        `| ${cell(entry.rotatePeriodDays)} days | ${entry.zeroDowntime === true ? 'yes' : 'no'} ` +
        `| ${rotationLink(entry.rotation)} |`,
    )
  }

  lines.push('', '## Where each one lives', '')
  for (const entry of entries) {
    lines.push(`### \`${cell(entry.env)}\``, '', cell(entry.stored), '')
    const slots = [
      ['version label', entry.versionEnv],
      ['retired key', entry.retiredEnv],
      ['retired version label', entry.retiredVersionEnv],
    ].filter(([, name]) => typeof name === 'string' && name !== '')
    if (slots.length > 0) {
      lines.push(
        `Rotation slots: ${slots.map(([what, name]) => `\`${name}\` (${what})`).join(', ')}.`,
        '',
      )
    }
    if (typeof entry.outage === 'string' && entry.outage !== '') {
      lines.push(`**If it is wrong or missing:** ${cell(entry.outage)}`, '')
    }
    if (typeof entry.notes === 'string' && entry.notes !== '') {
      lines.push(cell(entry.notes), '')
    }
  }

  lines.push(
    '## Deliberately not secrets',
    '',
    'Each of these is an environment variable something reads and this inventory classifies as not',
    'needing a rotation procedure. The reason is recorded rather than implied, because "it is not a',
    'secret" is the sentence somebody writes about a key that turns out to be one.',
    '',
  )
  for (const entry of notSecrets) {
    lines.push(`- **\`${cell(entry.name)}\`** — ${cell(entry.reason)}`)
  }
  lines.push('')
  return lines.join('\n')
}

const rendered = render()

if (EMIT) {
  mkdirSync(dirname(join(ROOT, PAGE)), { recursive: true })
  writeFileSync(join(ROOT, PAGE), rendered)
  console.log(
    `Wrote ${PAGE}: ${entries.length} entries, ${notSecrets.length} classified not-secrets.`,
  )
  process.exit(0)
}

let current = null
try {
  current = readFileSync(join(ROOT, PAGE), 'utf8')
} catch {
  current = null
}
if (current === null) {
  console.error(`${PAGE} does not exist. Run \`pnpm docs:secrets\`.`)
  process.exit(1)
}
if (current !== rendered) {
  const a = current.split('\n')
  const b = rendered.split('\n')
  const at = a.findIndex((line, i) => line !== b[i])
  console.error(
    `${PAGE}:${at + 1} is stale. Expected ${JSON.stringify(b[at] ?? '(end of file)')}, found ` +
      `${JSON.stringify(a[at] ?? '(end of file)')}. Run \`pnpm docs:secrets\`.`,
  )
  process.exit(1)
}

console.log(
  `Secret inventory page: current, ${entries.length} entries and ${notSecrets.length} classified ` +
    'not-secrets, generated from build/secret-inventory.json and holding no value of anything.',
)
